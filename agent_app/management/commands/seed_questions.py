class Command(BaseCommand):
    help = '初始化408题库数据'

    def handle(self, *args, **options):
        # 创建科目
        for slug, name in CATEGORIES:
            cat, created = Category.objects.get_or_create(slug=slug, defaults={'name': name, 'order': len(CATEGORIES)})
            if created:
                self.stdout.write(f'创建科目: {name}')
            # 更新排序
            cat.order = CATEGORIES.index((slug, name)) + 1
            cat.save()

        # 导入题目
        all_questions = [
            ('ds', DS_QUESTIONS),
            ('co', CO_QUESTIONS),
            ('os', OS_QUESTIONS),
            ('cn', CN_QUESTIONS),
        ]

        total = 0
        for slug, questions in all_questions:
            cat = Category.objects.get(slug=slug)
            for q in questions:
                Question.objects.get_or_create(
                    category=cat,
                    content=q[3],
                    defaults={
                        'qtype': q[0],
                        'difficulty': q[1],
                        'knowledge_point': q[2],
                        'option_a': q[4],
                        'option_b': q[5],
                        'option_c': q[6],
                        'option_d': q[7],
                        'answer': q[8],
                        'explanation': q[9],
                    }
                )
                total += 1

        self.stdout.write(self.style.SUCCESS(f'题库初始化完成！共导入 {total} 道题目'))
        self.stdout.write(f'  数据结构: {len(DS_QUESTIONS)} 题')
        self.stdout.write(f'  计算机组成原理: {len(CO_QUESTIONS)} 题')
        self.stdout.write(f'  操作系统: {len(OS_QUESTIONS)} 题')
        self.stdout.write(f'  计算机网络: {len(CN_QUESTIONS)} 题')
